create extension if not exists pgcrypto;

create table if not exists public.admin_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_profiles p
    where p.id = (select auth.uid()) and p.is_active = true
  );
$$;

revoke all on function public.is_active_admin() from public;
grant execute on function public.is_active_admin() to anon, authenticated;

create table if not exists public.tour_packages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) > 0),
  slug text not null unique check (length(trim(slug)) > 0),
  destination text not null check (length(trim(destination)) > 0),
  category text not null check (category in ('Domestik', 'Internasional')),
  duration text not null default '',
  video_url text,
  price_start bigint check (price_start is null or price_start >= 0),
  description text not null default '',
  itinerary jsonb not null default '[]'::jsonb check (jsonb_typeof(itinerary) = 'array'),
  inclusions jsonb not null default '[]'::jsonb check (jsonb_typeof(inclusions) = 'array'),
  exclusions jsonb not null default '[]'::jsonb check (jsonb_typeof(exclusions) = 'array'),
  cover_photo_path text,
  cover_photo_alt text not null default '',
  visible boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.tour_packages add column if not exists video_url text;

create index if not exists tour_packages_visible_order_idx
  on public.tour_packages (visible, sort_order, created_at desc);

create table if not exists public.customer_reviews (
  id uuid primary key default gen_random_uuid(),
  author text not null check (length(trim(author)) > 0),
  package_name text not null default '',
  quote text not null check (length(trim(quote)) > 0),
  rating smallint not null default 5 check (rating between 1 and 5),
  visible boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists customer_reviews_public_order_idx
  on public.customer_reviews (visible, created_at desc);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  visible boolean not null default true,
  sort_order integer not null default 0

drop policy if exists "admins can read their profile" on public.admin_profiles;
create policy "admins can read their profile" on public.admin_profiles
  for select to authenticated using (id = (select auth.uid()) or (select public.is_active_admin()));
drop policy if exists "admins can update their profile" on public.admin_profiles;
create policy "admins can update their profile" on public.admin_profiles
  for update to authenticated using (id = (select auth.uid()) and (select public.is_active_admin()))
  with check (id = (select auth.uid()) and (select public.is_active_admin()));

